export function doseFor(supp, bodyWeight) {
  if (!supp.doseByWeight || !bodyWeight) return supp.dose;
  const [lo, hi] = supp.doseByWeight;
  return `${Math.round(lo * bodyWeight)}–${Math.round(hi * bodyWeight)} мг за 45–60 минут до нагрузки`;
}

